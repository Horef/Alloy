# ---------------------------------------------------------------- code graph: calls, deps, map (Python only)
FUNC = (ast.FunctionDef, ast.AsyncFunctionDef)
DEFS = {ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef}
SKIP = {ast.Constant, ast.Load, ast.Store, ast.Del, ast.Pass, ast.alias, str, int, type(None)} | \
    {c for c in vars(ast).values() if isinstance(c, type) and issubclass(c, (ast.operator, ast.unaryop, ast.cmpop, ast.boolop))}
BUILTINS = set(dir(__import__("builtins")))
TYPE_METHODS = set().union(*(dir(t) for t in (dict, list, str, set, bytes, tuple)))  # x.get(), x.items(): too common to guess


class Def:
    def __init__(self, key, mod, qual, kind, node, cls=None):
        self.key, self.mod, self.qual, self.kind, self.node, self.cls = key, mod, qual, kind, node, cls
        self.line, self.end = node.lineno, getattr(node, "end_lineno", node.lineno)
        if kind == "class":
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            self.sig = f"class {node.name}" + (f"({bases})" if bases else "")
        else:
            ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
            self.sig = f"def {node.name}({ast.unparse(node.args)}){ret}"
        if len(self.sig) > 110:
            self.sig = self.sig[:107] + "..."


class Graph:
    """Definitions, resolved references and import edges of the repository's Python modules, built once per run.

    A reference is resolved through the module's imports (re-exports followed), `self`/`cls` in methods (base classes
    in the repo followed) and `x = Class(...)` in the same function. Anything else is kept by name only, never guessed."""

    def __init__(self, mods: dict[str, Module]):
        self.mods = mods
        self.defs: dict[str, Def] = {}
        self.scope: dict[str, dict[str, str]] = {}   # module -> local name -> dotted target
        self.refs = []      # (owner key, owner module, target key, line, is_call)
        self.byname = []    # (owner key, owner module, name, line, text): calls not resolved
        self.other = defaultdict(list)  # owner key -> external/builtin-free dotted names it calls
        for m in mods.values():
            if m.tree is not None:
                self.scope[m.name] = self._scope(m)
                self._collect(m.tree.body, m.name, "", None)
        self.bases = {k: [b for b in (self._resolve_static(d.mod, x) for x in d.node.bases) if b in self.defs]
                      for k, d in self.defs.items() if d.kind == "class"}
        for m in mods.values():
            if m.tree is not None:
                self._scan(m.name, m.name, m.tree, None)

    # -- definitions and module scopes
    def _collect(self, body, mod, prefix, cls):
        for n in body:
            if isinstance(n, FUNC + (ast.ClassDef,)):
                qual = prefix + n.name
                kind = "class" if isinstance(n, ast.ClassDef) else ("method" if cls else "def")
                self.defs[f"{mod}.{qual}"] = Def(f"{mod}.{qual}", mod, qual, kind, n, cls)
                self._collect(n.body, mod, qual + ".", f"{mod}.{qual}" if kind == "class" else None)
            elif isinstance(n, (ast.If, ast.Try, ast.With)):  # definitions under `if TYPE_CHECKING:`, try/except imports
                for part in ("body", "orelse", "finalbody"):
                    self._collect(getattr(n, part, []), mod, prefix, cls)
                for h in getattr(n, "handlers", []):
                    self._collect(h.body, mod, prefix, cls)

    def _scope(self, m: Module) -> dict[str, str]:
        names = {}
        for node in m.import_nodes:
            if isinstance(node, ast.Import):
                for a in node.names:
                    names[a.asname or a.name.split(".")[0]] = a.name if a.asname else a.name.split(".")[0]
            elif isinstance(node, ast.ImportFrom):
                base = resolve_relative(m.name, node.module, node.level, m.path.endswith("__init__.py"))
                for a in node.names:
                    if a.name != "*":
                        names[a.asname or a.name] = f"{base}.{a.name}" if base else a.name
        for n in m.tree.body:
            if isinstance(n, FUNC + (ast.ClassDef,)):
                names[n.name] = f"{m.name}.{n.name}"
        return names

    def canon(self, dotted: str, depth=0):
        """('def', key) | ('mod', name) | ('ext', dotted) | ('unres', dotted) for a dotted name."""
        if dotted in self.defs:
            return "def", dotted
        if dotted in self.mods:
            return "mod", dotted
        parts = dotted.split(".")
        for i in range(len(parts) - 1, 0, -1):
            mod = ".".join(parts[:i])
            if mod not in self.mods:
                continue
            rest = parts[i:]
            head = f"{mod}.{rest[0]}"
            if head in self.defs and len(rest) >= 2 and self.defs[head].kind == "class":
                k = self.method(head, rest[1])
                return ("def", k) if k and len(rest) == 2 else ("unres", dotted)
            target = self.scope.get(mod, {}).get(rest[0])
            if target and target != head and depth < 8:  # re-exported: follow the import
                return self.canon(".".join([target] + rest[1:]), depth + 1)
            return "unres", dotted
        return "ext", dotted

    def method(self, cls_key: str, name: str, seen=None):
        if f"{cls_key}.{name}" in self.defs:
            return f"{cls_key}.{name}"
        seen = seen or set()
        for b in self.bases.get(cls_key, []):
            if b not in seen:
                seen.add(b)
                k = self.method(b, name, seen)
                if k:
                    return k
        return None

    def _resolve_static(self, mod, expr):
        parts = dotted_parts(expr)
        if not parts or parts[0] not in self.scope.get(mod, {}):
            return None
        kind, k = self.canon(".".join([self.scope[mod][parts[0]]] + parts[1:]))
        return k if kind == "def" else None

    # -- references inside each owner (module body, class body, function body)
    def _scan(self, owner, mod, node, cls):
        """Resolve the references owned by `node` (not those inside nested defs), then scan the nested defs."""
        inner, callee, items, nested, local, types = set(), set(), [], [], set(), {}
        if isinstance(node, FUNC):
            a = node.args
            local = {x.arg for x in a.posonlyargs + a.args + a.kwonlyargs} | {x.arg for x in (a.vararg, a.kwarg) if x}
        stack = list(node.body)
        while stack:
            n = stack.pop()
            t = type(n)
            if t in SKIP:
                continue
            if t in DEFS:
                nested.append(n)
                stack.extend(n.decorator_list + (n.bases if isinstance(n, ast.ClassDef) else []))
                continue
            if t is ast.Attribute:
                inner.add(id(n.value))
            elif t is ast.Call:
                callee.add(id(n.func))
            elif t is ast.Assign and isinstance(node, FUNC) and len(n.targets) == 1 \
                    and isinstance(n.targets[0], ast.Name) and isinstance(n.value, ast.Call):
                k = self._resolve_static(mod, n.value.func)  # x = Class(...): x.method() resolves
                if k and self.defs[k].kind == "class":
                    types[n.targets[0].id] = k
            if t is ast.Name or t is ast.Attribute:
                ctx = type(n.ctx)
                if ctx is ast.Load:
                    if id(n) not in inner:
                        items.append(n)
                elif t is ast.Name and isinstance(node, FUNC):
                    local.add(n.id)
                if t is ast.Name:
                    continue
            for f in n._fields:  # ast.iter_child_nodes, inlined: this loop is most of the run time
                v = getattr(n, f, None)
                if type(v) is list:
                    stack.extend(v)
                elif isinstance(v, ast.AST):
                    stack.append(v)
        key_of = {n.name: f"{mod}.{n.name}" if owner == mod else f"{owner}.{n.name}" for n in nested}
        here = key_of if isinstance(node, FUNC) else {}  # functions and classes defined in this function
        for n in items:
            self._ref(owner, mod, n, id(n) in callee, cls, local, types, here)
        for n in nested:
            key = key_of[n.name]
            self._scan(key, mod, n, key if isinstance(n, ast.ClassDef) else (cls if isinstance(node, ast.ClassDef) else None))

    def _ref(self, owner, mod, n, is_call, cls, local, types, here):
        parts = dotted_parts(n)
        text = ".".join(parts) if parts else ast.unparse(n)
        line = n.lineno
        if not parts:  # e.g. f(x).g(): only the attribute name is known
            if is_call and isinstance(n, ast.Attribute):
                self.byname.append((owner, mod, n.attr, line, text))
            return
        first, target = parts[0], None
        if first in ("self", "cls") and cls and first in local and len(parts) == 2:
            target = self.method(cls, parts[1])
        elif first in here and first not in local:
            target = here[first] if len(parts) == 1 else self.method(here[first], parts[1]) if len(parts) == 2 else None
        elif first in types and len(parts) == 2:
            target = self.method(types[first], parts[1])
        elif first in local and first not in types:
            if is_call and len(parts) > 1:
                self.byname.append((owner, mod, parts[-1], line, text))
            return
        elif first in self.scope.get(mod, {}):
            kind, k = self.canon(".".join([self.scope[mod][first]] + parts[1:]))
            if kind == "def":
                target = k
            elif kind == "ext":
                if is_call:
                    self.other[owner].append(k)
                return
            elif kind == "mod":
                return
        elif first in BUILTINS and len(parts) == 1:
            return
        if target:
            self.refs.append((owner, mod, target, line, is_call))
        elif is_call:
            self.byname.append((owner, mod, parts[-1], line, text))


def dotted_parts(expr):
    if isinstance(expr, ast.Name):
        return [expr.id]
    if isinstance(expr, ast.Attribute):
        head = dotted_parts(expr.value)
        return head + [expr.attr] if head else None
    return None


def find_defs(g: Graph, name: str) -> list[Def]:
    if ":" in name:  # path.py:Qual.name
        path, _, qual = name.partition(":")
        return [d for d in g.defs.values() if g.mods[d.mod].path == path.removeprefix("./") and d.qual == qual]
    if name in g.defs:
        return [g.defs[name]]
    return sorted((d for d in g.defs.values() if d.key.endswith("." + name)), key=lambda d: d.key)


